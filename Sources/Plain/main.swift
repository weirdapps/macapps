import AppKit
import Combine
import Kit
import SwiftUI

IconKit.handleCommandLine(draw: appIcon)

MainActor.assumeIsolated {
    let app = NSApplication.shared
    let delegate = AppDelegate()
    app.delegate = delegate
    app.setActivationPolicy(.accessory)
    app.run()
}

@MainActor
final class AppDelegate: NSObject, NSApplicationDelegate {
    private var status: StatusPopover!
    private var cancellables: Set<AnyCancellable> = []
    let cleaner = ClipboardCleaner()

    func applicationDidFinishLaunching(_ notification: Notification) {
        status = StatusPopover(symbol: "doc.plaintext", accessibilityLabel: "Plain") {
            PlainView().environmentObject(self.cleaner)
        }
        cleaner.$paused.sink { [weak self] paused in
            self?.status.setSymbol(paused ? "pause.circle" : "doc.plaintext", label: paused ? "Plain paused" : "Plain")
        }
        .store(in: &cancellables)
        // A brief sparkle in the menu bar each time something is cleaned.
        cleaner.didClean.sink { [weak self] in
            guard let self else { return }
            self.status.setSymbol("sparkles", label: "Cleaned")
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.9) {
                self.status.setSymbol(self.cleaner.paused ? "pause.circle" : "doc.plaintext", label: "Plain")
            }
        }
        .store(in: &cancellables)
    }
}

// MARK: - Model

struct Cleaning: Codable, Identifiable {
    var id = UUID()
    var date = Date()
    var text: String
    var formatting: Bool
    var trackers: Int
    var whitespace: Bool
}

struct Totals: Codable {
    var cleaned = 0
    var trackers = 0
    var formatting = 0
}

@MainActor
final class ClipboardCleaner: ObservableObject {
    @Published var paused = false
    @Published private(set) var history: [Cleaning] = []
    @Published private(set) var totals = Totals()
    @AppStorage("stripFormatting") var stripFormatting = true
    @AppStorage("cleanLinks") var cleanLinks = true
    @AppStorage("trimWhitespace") var trimWhitespace = true

    let didClean = PassthroughSubject<Void, Never>()

    private let pasteboard = NSPasteboard.general
    private var lastChange: Int
    private var timer: Timer?
    private var resumeWork: DispatchWorkItem?

    /// Types that password managers and other apps use to ask clipboard tools to keep out.
    private static let privateTypes: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.ConcealedType"), .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"), .init("com.agilebits.onepassword"),
    ]
    private static let richTypes: [NSPasteboard.PasteboardType] = [.rtf, .rtfd, .html, .init("com.apple.flat-rtfd"), .init("com.apple.webarchive")]
    private static let skipTypes: [NSPasteboard.PasteboardType] = [.fileURL, .tiff, .png, .pdf]

    init() {
        lastChange = pasteboard.changeCount
        if StatusPopover.isSnapshot {
            // Fixed demo data for screenshots: never the user's clipboard, and the clipboard is not watched.
            history = ClipboardCleaner.demoHistory
            totals = Totals(cleaned: 128, trackers: 46, formatting: 71)
            return
        }
        history = Storage.load([Cleaning].self, app: "Plain", file: "history.json") ?? []
        totals = Storage.load(Totals.self, app: "Plain", file: "totals.json") ?? Totals()
        timer = Timer.scheduledTimer(withTimeInterval: 0.35, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
    }

    private static let demoHistory: [Cleaning] = [
        Cleaning(date: Date(timeIntervalSinceNow: -40), text: "https://www.youtube.com/watch?v=aqz-KE-bpKQ",
                 formatting: false, trackers: 2, whitespace: false),
        Cleaning(date: Date(timeIntervalSinceNow: -300), text: "The meeting moved to Thursday at 10:00, same room.",
                 formatting: true, trackers: 0, whitespace: true),
        Cleaning(date: Date(timeIntervalSinceNow: -1500), text: "Read this: https://example.com/article/swift-concurrency",
                 formatting: true, trackers: 3, whitespace: false),
        Cleaning(date: Date(timeIntervalSinceNow: -4000), text: "brew install --cask visual-studio-code",
                 formatting: false, trackers: 0, whitespace: true),
    ]

    func pause(for minutes: Int?) {
        resumeWork?.cancel()
        paused = true
        guard let minutes else { return }
        let work = DispatchWorkItem { [weak self] in self?.paused = false }
        resumeWork = work
        DispatchQueue.main.asyncAfter(deadline: .now() + .seconds(minutes * 60), execute: work)
    }

    func resume() {
        resumeWork?.cancel()
        paused = false
    }

    func copy(_ text: String) {
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        lastChange = pasteboard.changeCount
    }

    func clearHistory() {
        history = []
        Storage.save(history, app: "Plain", file: "history.json")
    }

    /// Clean whatever is on the clipboard now, even when paused.
    func cleanNow() { process(force: true) }

    private func poll() {
        guard pasteboard.changeCount != lastChange else { return }
        lastChange = pasteboard.changeCount
        if !paused { process(force: false) }
    }

    private func process(force: Bool) {
        let types = pasteboard.types ?? []
        if types.contains(where: ClipboardCleaner.privateTypes.contains) { return }
        if types.contains(where: ClipboardCleaner.skipTypes.contains) && !force { return }
        guard let original = pasteboard.string(forType: .string), !original.isEmpty else { return }

        let rich = stripFormatting && types.contains(where: ClipboardCleaner.richTypes.contains)
        var text = original
        var trackers = 0
        if cleanLinks {
            let result = LinkCleaner.clean(text)
            text = result.text
            trackers = result.removed
        }
        var trimmed = false
        if trimWhitespace {
            let t = ClipboardCleaner.trimmed(text)
            trimmed = t != text && !t.isEmpty
            if trimmed { text = t }
        }
        guard rich || trackers > 0 || trimmed else { return }

        if !rich && !stripFormatting && types.contains(where: ClipboardCleaner.richTypes.contains) {
            // Formatting is kept: only links or spacing changed, so leave rich data untouched.
            return
        }
        copy(text)
        record(Cleaning(text: text, formatting: rich, trackers: trackers, whitespace: trimmed))
    }

    /// Drops trailing whitespace and leading blank lines, keeping the first line's indentation so pasted code still works.
    static func trimmed(_ text: String) -> String {
        var t = Substring(text)
        while let c = t.last, c.isWhitespace { t.removeLast() }
        while let nl = t.firstIndex(where: \.isNewline), t[..<nl].allSatisfy(\.isWhitespace) { t = t[t.index(after: nl)...] }
        return String(t)
    }

    private func record(_ entry: Cleaning) {
        withAnimation(.snappy) {
            history.insert(entry, at: 0)
            if history.count > 30 { history.removeLast(history.count - 30) }
            totals.cleaned += 1
            totals.trackers += entry.trackers
            if entry.formatting { totals.formatting += 1 }
        }
        Storage.save(history, app: "Plain", file: "history.json")
        Storage.save(totals, app: "Plain", file: "totals.json")
        didClean.send()
    }
}

// MARK: - Views

struct PlainView: View {
    @EnvironmentObject var cleaner: ClipboardCleaner

    var body: some View {
        VStack(spacing: 0) {
            header
            pauseBar
            Divider().opacity(0.5)
            if cleaner.history.isEmpty {
                VStack(spacing: 8) {
                    Image(systemName: "sparkles").font(.system(size: 28)).foregroundStyle(.tertiary)
                    Text("Copy something with formatting or a tracking link,\nand the clean version will show up here.")
                        .font(.system(size: 12)).foregroundStyle(.secondary).multilineTextAlignment(.center)
                }
                .frame(maxWidth: .infinity)
                .frame(height: 180)
            } else {
                ScrollView {
                    VStack(spacing: 4) {
                        ForEach(cleaner.history.prefix(12)) { entry in
                            HistoryRow(entry: entry)
                        }
                    }
                    .padding(8)
                }
                .frame(height: 260)
            }
            Divider().opacity(0.5)
            PanelFooter(name: "Plain") {
                Toggle("Remove Formatting", isOn: $cleaner.stripFormatting)
                Toggle("Remove Link Trackers", isOn: $cleaner.cleanLinks)
                Toggle("Trim Spaces and Blank Lines", isOn: $cleaner.trimWhitespace)
                Divider()
                Button("Clean Clipboard Now") { cleaner.cleanNow() }
                Button("Clear History") { cleaner.clearHistory() }
            }
        }
        .frame(width: 360)
    }

    private var header: some View {
        HStack(alignment: .center, spacing: 14) {
            VStack(alignment: .leading, spacing: 2) {
                Text(cleaner.totals.cleaned.formatted())
                    .font(.system(size: 30, weight: .bold, design: .rounded))
                    .contentTransition(.numericText())
                Text("copies cleaned").font(.system(size: 11, weight: .medium)).foregroundStyle(.secondary)
            }
            Spacer()
            VStack(alignment: .trailing, spacing: 5) {
                StatChip(symbol: "link", value: cleaner.totals.trackers, label: "trackers")
                StatChip(symbol: "textformat", value: cleaner.totals.formatting, label: "formats")
            }
        }
        .padding(.horizontal, 16)
        .padding(.top, 14)
        .padding(.bottom, 10)
    }

    private var pauseBar: some View {
        HStack(spacing: 8) {
            Circle().fill(cleaner.paused ? Color.orange : .green).frame(width: 7, height: 7)
            Text(cleaner.paused ? "Paused" : "Watching the clipboard")
                .font(.system(size: 11, weight: .medium)).foregroundStyle(.secondary)
            Spacer()
            if cleaner.paused {
                Button("Resume") { cleaner.resume() }.buttonStyle(.plain).font(.system(size: 11, weight: .semibold)).foregroundStyle(Color.accentColor)
            } else {
                Menu("Pause") {
                    Button("For 5 Minutes") { cleaner.pause(for: 5) }
                    Button("For 1 Hour") { cleaner.pause(for: 60) }
                    Button("Until I Resume") { cleaner.pause(for: nil) }
                }
                .menuStyle(.borderlessButton)
                .menuIndicator(.hidden)
                .fixedSize()
                .font(.system(size: 11, weight: .semibold))
            }
        }
        .padding(.horizontal, 16)
        .padding(.bottom, 10)
    }
}

struct StatChip: View {
    let symbol: String
    let value: Int
    let label: String

    var body: some View {
        HStack(spacing: 4) {
            Image(systemName: symbol).font(.system(size: 9, weight: .bold))
            Text("\(value.formatted()) \(label)").font(.system(size: 11, weight: .semibold, design: .rounded)).monospacedDigit()
        }
        .foregroundStyle(Color(red: 0.05, green: 0.6, blue: 0.55))
        .padding(.horizontal, 8)
        .padding(.vertical, 3)
        .background(Capsule().fill(Color(red: 0.05, green: 0.6, blue: 0.55).opacity(0.13)))
    }
}

struct HistoryRow: View {
    @EnvironmentObject var cleaner: ClipboardCleaner
    let entry: Cleaning
    @State private var hovering = false
    @State private var copied = false

    var body: some View {
        Button {
            cleaner.copy(entry.text)
            withAnimation { copied = true }
            DispatchQueue.main.asyncAfter(deadline: .now() + 1) { withAnimation { copied = false } }
        } label: {
            HStack(alignment: .top, spacing: 10) {
                VStack(alignment: .leading, spacing: 4) {
                    Text(entry.text.replacingOccurrences(of: "\n", with: " "))
                        .font(.system(size: 12))
                        .lineLimit(2)
                        .truncationMode(.middle)
                        .frame(maxWidth: .infinity, alignment: .leading)
                    HStack(spacing: 5) {
                        if entry.formatting { Badge("Formatting") }
                        if entry.trackers > 0 { Badge("\(entry.trackers) tracker\(entry.trackers == 1 ? "" : "s")") }
                        if entry.whitespace { Badge("Spacing") }
                        Text(entry.date, style: .relative).font(.system(size: 10)).foregroundStyle(.tertiary)
                    }
                }
                Image(systemName: copied ? "checkmark.circle.fill" : "doc.on.doc")
                    .font(.system(size: 12))
                    .foregroundStyle(copied ? AnyShapeStyle(.green) : AnyShapeStyle(.secondary))
                    .opacity(hovering || copied ? 1 : 0)
            }
            .padding(10)
            .background(RoundedRectangle(cornerRadius: 10, style: .continuous).fill(.quaternary.opacity(hovering ? 0.55 : 0.28)))
            .contentShape(Rectangle())
        }
        .buttonStyle(.plain)
        .help("Copy again")
        .onHover { hovering = $0 }
    }
}

struct Badge: View {
    let text: String
    init(_ text: String) { self.text = text }

    var body: some View {
        Text(text)
            .font(.system(size: 9.5, weight: .semibold, design: .rounded))
            .foregroundStyle(.secondary)
            .padding(.horizontal, 6)
            .padding(.vertical, 1.5)
            .background(Capsule().fill(.quaternary.opacity(0.8)))
    }
}

// MARK: - Icon

//: a clean page and sparkles

func appIcon() -> NSBitmapImageRep {
    render(0x3DDBA4, 0x0B7C8E) { ctx in
        let page = CGRect(x: 300, y: 230, width: 400, height: 520)
        let fold: CGFloat = 110
        let outline = CGMutablePath()
        outline.move(to: CGPoint(x: page.minX + 40, y: page.minY))
        outline.addLine(to: CGPoint(x: page.maxX - 40, y: page.minY))
        outline.addQuadCurve(to: CGPoint(x: page.maxX, y: page.minY + 40), control: CGPoint(x: page.maxX, y: page.minY))
        outline.addLine(to: CGPoint(x: page.maxX, y: page.maxY - fold))
        outline.addLine(to: CGPoint(x: page.maxX - fold, y: page.maxY))
        outline.addLine(to: CGPoint(x: page.minX + 40, y: page.maxY))
        outline.addQuadCurve(to: CGPoint(x: page.minX, y: page.maxY - 40), control: CGPoint(x: page.minX, y: page.maxY))
        outline.addLine(to: CGPoint(x: page.minX, y: page.minY + 40))
        outline.addQuadCurve(to: CGPoint(x: page.minX + 40, y: page.minY), control: CGPoint(x: page.minX, y: page.minY))
        ctx.saveGState()
        shadow(ctx, y: -18, blur: 34, alpha: 0.3)
        ctx.addPath(outline)
        ctx.setFillColor(NSColor.white.cgColor)
        ctx.fillPath()
        ctx.restoreGState()
        // Folded corner.
        ctx.move(to: CGPoint(x: page.maxX, y: page.maxY - fold))
        ctx.addLine(to: CGPoint(x: page.maxX - fold + 18, y: page.maxY - fold))
        ctx.addQuadCurve(to: CGPoint(x: page.maxX - fold, y: page.maxY - fold + 18), control: CGPoint(x: page.maxX - fold, y: page.maxY - fold))
        ctx.addLine(to: CGPoint(x: page.maxX - fold, y: page.maxY))
        ctx.closePath()
        ctx.setFillColor(rgb(0xCFEFEA).cgColor)
        ctx.fillPath()
        // Plain text lines.
        ctx.setStrokeColor(rgb(0x9DB8BF).cgColor)
        ctx.setLineWidth(22)
        ctx.setLineCap(.round)
        for (i, w) in [220.0, 300, 270, 300, 190].enumerated() {
            let y = page.maxY - 170 - CGFloat(i) * 62
            ctx.move(to: CGPoint(x: page.minX + 60, y: y)); ctx.addLine(to: CGPoint(x: page.minX + 60 + w, y: y))
        }
        ctx.strokePath()
        ctx.saveGState()
        shadow(ctx, y: -4, blur: 16, alpha: 0.18)
        sparkle(ctx, at: CGPoint(x: 735, y: 760), size: 92, color: rgb(0xFFF6C2))
        sparkle(ctx, at: CGPoint(x: 820, y: 620), size: 46, color: .white)
        sparkle(ctx, at: CGPoint(x: 230, y: 330), size: 52, color: rgb(0xFFF6C2))
        ctx.restoreGState()
    }
}
